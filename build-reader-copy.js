/* Builds the plain-text copy of the story that lives in the WordPress post.

   Why it exists: the story runs inside an iframe, and browser reader views
   (Safari Reader, Firefox Reader View, Chrome reading mode) only read the
   post itself, never a frame inside it. So the post carries its own copy of
   every word, visually hidden, between the st-text markers in
   wordpress-embed-snippet.html. Screen readers read that copy instead of the
   frame (the snippet hides the frame from them), so they hear it once.

   It's generated from senior-tips.html rather than written by hand so the
   two can't drift apart. Run it after any copy change, then re-paste the
   snippet into the post:

     npm install      (once)
     node build-reader-copy.js
*/
const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");

const STORY = path.join(__dirname, "senior-tips.html");
const SNIPPET = path.join(__dirname, "wordpress-embed-snippet.html");
const START = "<!-- st-text:start (generated by build-reader-copy.js; edit senior-tips.html, not this) -->";
const END = "<!-- st-text:end -->";

const doc = new JSDOM(fs.readFileSync(STORY, "utf8")).window.document;

// Only these tags and attributes survive into the copy.
const KEEP = {
  P: [], STRONG: [], EM: [], BR: [], UL: [], OL: [], LI: [],
  H2: ["id"], H3: ["id"], H4: [],
  A: ["href"],
  IMG: ["src", "alt", "width", "height"],
};

function clean(node) {
  if (node.nodeType === 3) return escape(node.textContent);
  if (node.nodeType !== 1) return "";
  const inner = [...node.childNodes].map(clean).join("");
  const attrs = KEEP[node.tagName];
  if (!attrs) return inner; // unwrap anything else (spans, sections, divs)
  const tag = node.tagName.toLowerCase();
  let out = "<" + tag;
  for (const name of attrs) {
    if (!node.hasAttribute(name)) continue;
    let value = node.getAttribute(name);
    if (name === "id") value = "st-text-" + value;
    if (name === "href" && value.startsWith("#")) {
      // In-page links point at this copy's own sections; bare "#"
      // placeholders are dropped (the words stay).
      if (value === "#") return inner;
      value = "#st-text-" + value.slice(1);
    }
    out += ` ${name}="${escape(value)}"`;
  }
  // Keyboard users who can see the page tab through the real story in the
  // frame; this copy's links stay reachable for screen readers by reading,
  // just not in the visible tab order, where focus would land on nothing.
  if (tag === "a") out += ' tabindex="-1"';
  // Links that leave the page open in a new tab, as they do in the story.
  if (tag === "a" && /^https?:/i.test(node.getAttribute("href") || "")) {
    out += ' target="_blank" rel="noopener"';
  }
  if (tag === "img") return out + ' loading="lazy">';
  return out + ">" + inner + "</" + tag + ">";
}

function escape(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

const parts = [];

// Subhead and intro.
parts.push(`<p><strong>${escape(doc.querySelector(".hero .subhead").textContent.trim())}</strong></p>`);
doc.querySelectorAll(".intro__copy .copy__inner > p").forEach((p) => parts.push(clean(p)));

// The printable PDF link, which sits at the end of the contents in the story.
const print = doc.querySelector(".toc__print");
if (print) parts.push(clean(print));

// Each person's tips: their name as a heading, the portrait, the tips.
doc.querySelectorAll("section.tips").forEach((section) => {
  const name = section.querySelector(".tips__label .art-text").textContent.trim();
  parts.push(`<h2 id="st-text-${section.id}">${escape(name)}</h2>`);
  const cutout = section.querySelector(".tips__cutout");
  if (cutout) parts.push(clean(cutout));
  parts.push(clean(section.querySelector(".bubble__tips")));
});

// The resources section, as is. The pictures beside its group headings are
// decoration (their alt is empty), so only the words come along.
doc.querySelectorAll(".copy--resources .copy__inner > *").forEach((el) => {
  if (el.tagName === "H3" && el.querySelector("img")) {
    const id = el.id ? ` id="st-text-${el.id}"` : "";
    parts.push(`<h3${id}>${escape(el.textContent.trim())}</h3>`);
  } else {
    parts.push(clean(el));
  }
});

const block = [
  START,
  '<div id="st-text" class="st-reader-copy">',
  ...parts.map((p) => "  " + p.replace(/\s+/g, " ").trim()),
  "</div>",
  END,
].join("\n");

let snippet = fs.readFileSync(SNIPPET, "utf8");
const a = snippet.indexOf(START);
const b = snippet.indexOf(END);
if (a === -1 || b === -1) throw new Error("st-text markers not found in " + SNIPPET);
snippet = snippet.slice(0, a) + block + snippet.slice(b + END.length);
fs.writeFileSync(SNIPPET, snippet);
console.log(`Wrote ${parts.length} blocks (${block.length} chars) into wordpress-embed-snippet.html`);
